#!/usr/bin/env node
// Writes .env.local for the frontend (Vite) from a cloud project's env file (`--target verify`,
// the default, or `--target demo`; `npm run demo:frontend-env`), using ONLY the public
// values: the project URL and the publishable (anon) key. Secret keys never go into the
// frontend. Values are never printed.
//
//   npm run cloud:frontend-env            (refuses to overwrite an existing .env.local)
//   npm run cloud:frontend-env -- --force
//   npm run cloud:frontend-env -- --force --demo   demo mode with the account switcher; needs
//       demo-login.local from `npm run demo -- seed`. The demo password is then in the build:
//       build and share such a version only for a demo project.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadCloudTarget, ROOT as root } from './cloud-target.mjs';

const { fileName } = loadCloudTarget();
const target = join(root, '.env.local');
const force = process.argv.includes('--force');
const demo = process.argv.includes('--demo');
const demoLogin = join(root, 'demo-login.local');

const url = (process.env.SUPABASE_URL ?? '').replace(/\/$/, '');
const key = process.env.SUPABASE_PUBLISHABLE_KEY ?? '';

/** True only for keys that are public by design. */
function isPublicKey(k) {
  if (k.startsWith('sb_publishable_')) return true;
  if (k.startsWith('sb_secret_')) return false;
  // Legacy JWT keys: only role "anon" is public; "service_role" bypasses RLS.
  const payload = k.split('.')[1];
  if (!payload) return false;
  try {
    return JSON.parse(Buffer.from(payload, 'base64url').toString()).role === 'anon';
  } catch {
    return false;
  }
}

if (!/^https:\/\/[a-z0-9]+\.supabase\.co$/.test(url)) {
  console.error(`SUPABASE_URL in ${fileName} does not look like https://<ref>.supabase.co`);
  process.exit(1);
}
if (!isPublicKey(key)) {
  console.error(
    'SUPABASE_PUBLISHABLE_KEY is not a publishable/anon key. Refusing to put it into the frontend.',
  );
  process.exit(1);
}
if (existsSync(target) && !force) {
  console.error('.env.local already exists. Re-run with -- --force to overwrite it.');
  process.exit(1);
}

let demoLines = 'VITE_DEMO_MODE=false\n';
if (demo) {
  const password = existsSync(demoLogin)
    ? readFileSync(demoLogin, 'utf8')
        .split(/\r?\n/)
        .find((l) => l.startsWith('password='))
        ?.slice('password='.length)
    : undefined;
  const project = existsSync(demoLogin)
    ? readFileSync(demoLogin, 'utf8')
        .match(/^project=(.*)$/m)?.[1]
        ?.replace(/\/$/, '')
    : undefined;
  if (!password || project !== url) {
    console.error(
      `demo-login.local is missing or belongs to another project: run \`npm run demo -- seed --yes\` for ${fileName} first.`,
    );
    process.exit(1);
  }
  demoLines = [
    '# Demo mode: the demo password below is public in this build. Demo projects only.',
    'VITE_DEMO_MODE=true',
    `VITE_DEMO_PASSWORD=${password}`,
    '',
  ].join('\n');
}

writeFileSync(
  target,
  `# Generated by \`npm run cloud:frontend-env\` from ${fileName} (public values only).
# Git-ignored. The publishable key is public by design: Row Level Security protects the data.
VITE_SUPABASE_URL=${url}
VITE_SUPABASE_ANON_KEY=${key}
VITE_MAP_STYLE_URL=https://tiles.openfreemap.org/styles/liberty
VITE_GEOCODER_PROVIDER=nominatim
VITE_GEOCODER_URL=https://nominatim.openstreetmap.org
VITE_GEOCODER_COUNTRYCODES=de
${demoLines}`,
);
console.log(
  `Wrote .env.local (project URL + publishable key${demo ? ', demo mode on' : ''}; no server secrets).`,
);
